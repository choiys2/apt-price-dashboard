CODE_TO_NAME = {code: (sido, sgg) for code, sido, sgg in REGIONS + OLD_CODES}


def regions(sido=None):
    """시도명으로 필터링한 (code, sido, sgg) 목록. sido=None이면 수도권 전체."""
    if not sido:
        return list(REGIONS)
    wanted = {sido} if isinstance(sido, str) else set(sido)
    return [r for r in REGIONS if r[1] in wanted]


def region_name(code):
    sido, sgg = CODE_TO_NAME.get(code, ("", code))
    return f"{sido} {sgg}".strip()


if __name__ == "__main__":
    for sido in SIDO_ORDER:
        n = len(regions(sido))
        print(f"{sido}: {n}개")
    print(f"합계: {len(REGIONS)}개 시군구")
